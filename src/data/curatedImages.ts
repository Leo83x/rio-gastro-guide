export function getCuratedCoverImage(category: RestaurantCategory, index = 0): string {
  const list = CURATED_CATEGORY_IMAGES[category] ?? CURATED_CATEGORY_IMAGES.Contemporâneo;
  return list[Math.abs(index) % list.length];
}

export function getCuratedGallery(category: RestaurantCategory, index = 0): string[] {
  const list = CURATED_CATEGORY_IMAGES[category] ?? CURATED_CATEGORY_IMAGES.Contemporâneo;
  const start = Math.abs(index) % list.length;
  return [
    list[start],
    list[(start + 1) % list.length],
    list[(start + 2) % list.length],
  ];
}
