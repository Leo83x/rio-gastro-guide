import { SEED_RESTAURANTS } from './seedRestaurants';

const ENRICHED_GASTRONOMY: Experience[] = SEED_RESTAURANTS.map((r) => {
  const isBudget = r.price_range === '$' || r.price_range === '$$';
  const isBoteco = r.category === 'Boteco Carioca';
  const isFamilyFriendly =
    r.category === 'Pizzaria' || r.category === 'Cafeteria' || r.category === 'Churrascaria' || r.category === 'Brasileiro';

  const moment_tags: Experience['moment_tags'] = ['all'];
  if (isFamilyFriendly) moment_tags.push('family');
  if (r.price_range === '$$$' || r.price_range === '$$$$') moment_tags.push('couple');
  if (isBoteco || r.category === 'Pizzaria') moment_tags.push('friends');
  if (r.is_featured || r.neighborhood === 'Copacabana' || r.neighborhood === 'Centro' || r.neighborhood === 'Urca') {
    moment_tags.push('tourist');
  }
  if (!isBoteco) moment_tags.push('rainy'); // Salão coberto
  if (isBudget) moment_tags.push('budget');

  return {
    ...r,
    macro_category: 'Gastronomia',
    moment_tags,
    data_reliability: 'ESTABLISHMENT_PROVIDED',
    rating_source: 'seed_editorial',
    image_origin: 'illustrative_editorial',
    image_license: 'Banco editorial ilustrativo (Seed Demonstração)',
    has_real_photo: true,
    attributes: {
      is_covered: r.slug !== 'bar-urca',
      is_free: false,
      is_kid_friendly: isFamilyFriendly,
      has_parking: r.neighborhood === 'Barra da Tijuca' || r.neighborhood === 'Copacabana',
      parking_avg_cost: r.neighborhood === 'Copacabana' ? 'R$ 30 (valet)' : undefined,
      avg_ticket_brl:
        r.price_range === '$' ? 65 : r.price_range === '$$' ? 120 : r.price_range === '$$$' ? 240 : 420,
      duration_minutes: 90,
      off_peak_window: 'Ter–Qui 18h–20h',
    },
  };
});

